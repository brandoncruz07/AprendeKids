type Vars = Record<string, string>
const Ctx = createContext({ lang: 'es' as Lang, setLang: (_: Lang) => {}, t: (k: string, _v?: Vars) => k })

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem('ak_lang') as Lang | null
      return saved && LANGS.some((item) => item.id === saved) ? saved : 'es'
    } catch { return 'es' }
  })
  useEffect(() => {
    try { localStorage.setItem('ak_lang', lang) } catch {}
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
  }, [lang])
  const t = (k: string, v: Vars = {}) => (D[lang][k] ?? D.en[k] ?? k).replace(/\{(\w+)\}/g, (_, x) => v[x] ?? '')
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}
export const useI18n = () => useContext(Ctx)

export function LangSwitch() {
  const { lang, setLang } = useI18n()
  return (
    <>
      <label className="sr-only" htmlFor="language-select">Language / Idioma</label>
      <select
        id="language-select"
        value={lang}
        onChange={(event) => {
          const selected = LANGS.find((item) => item.id === event.target.value)
          if (selected) setLang(selected.id)
        }}
        className="max-w-32 rounded-xl border-2 border-yellow-300 bg-white px-2 py-2 text-sm font-bold shadow"
      >
        {LANGS.map((item) => <option key={item.id} value={item.id}>{item.flag} {item.label}</option>)}
      </select>
    </>
  )
}
